class SummarizeRequest(BaseModel):
    raw_text: str = Field(..., description="Original raw or scraped scholarship eligibility text")


class SummarizeResponse(BaseModel):
    summary: str = Field(..., description="Simple English scholarship eligibility summary")
    confidence_score: Optional[float] = Field(None, ge=0.0, le=1.0, description="Data-quality confidence score")
    warnings: List[str] = Field(default_factory=list, description="Quality warnings or missing criteria")
    extracted_facts: Optional[Dict[str, Any]] = Field(None, description="Structured signals detected from text")
    is_fallback: bool = Field(False, description="True if generated by deterministic template fallback")
    provider: str = Field("deterministic-fallback", description="LLM model or fallback provider used")


class CandidateItem(BaseModel):
    id: Optional[str] = None
    scheme_name: Optional[str] = None
    title: Optional[str] = None
    provider: Optional[str] = None
    award_amount: Optional[float] = None
    award_amount_inr: Optional[float] = None
    deadline: Optional[str] = None
    apply_link: Optional[str] = None
    official_url: Optional[str] = None
    raw_eligibility_text: Optional[str] = None
    llm_summary: Optional[str] = None
    summary: Optional[str] = None
    required_documents: List[str] = Field(default_factory=list)
    confidence_score: Optional[float] = None
    eligibility_score: Optional[float] = None

    model_config = {"extra": "allow"}

    def to_dict(self) -> Dict[str, Any]:
        d = self.model_dump()
        if not d.get("scheme_name") and d.get("title"):
            d["scheme_name"] = d["title"]
        if d.get("award_amount") is None and d.get("award_amount_inr") is not None:
            d["award_amount"] = d["award_amount_inr"]
        if not d.get("apply_link") and d.get("official_url"):
            d["apply_link"] = d["official_url"]
        if not d.get("llm_summary") and d.get("summary"):
            d["llm_summary"] = d["summary"]
        return d


class RankRequest(BaseModel):
    candidates: Optional[List[CandidateItem]] = None
    schemes: Optional[List[CandidateItem]] = None
    items: Optional[List[CandidateItem]] = None

    def get_candidates(self) -> List[Dict[str, Any]]:
        raw_list = self.candidates or self.schemes or self.items or []
        return [c.to_dict() for c in raw_list]


class RankedCandidateItem(BaseModel):
    id: Optional[str] = None
    scheme_name: str
    provider: Optional[str] = None
    award_amount: Optional[float] = None
    deadline: Optional[str] = None
    apply_link: Optional[str] = None
    raw_eligibility_text: Optional[str] = None
    llm_summary: Optional[str] = None
    required_documents: List[str] = Field(default_factory=list)
    confidence_score: Optional[float] = None
    eligibility_score: Optional[float] = None
    rank: int
    rank_score: float
    score_explanation: Dict[str, Any]
    disclaimer: str

    model_config = {"extra": "allow"}


class RankResponse(BaseModel):
    total: int
    ranked_candidates: List[RankedCandidateItem]
